function isRussianHomePage() {
  const path = window.location.pathname.replace(/\/$/, "") || "/"
  return path === "" || path === "/" || path === "/index.html"
}

function getCurrentLanguage() {
  if (isRussianHomePage()) return "ru"
  const saved = localStorage.getItem("tabskin-language")
  if (saved === "ru" || saved === "en") return saved
  const browserLang = (navigator.language || navigator.userLanguage || "").toLowerCase()
  if (browserLang.startsWith("ru")) return "ru"
  if (browserLang.startsWith("en")) return "en"
  return "ru"
}

function setLanguage(lang) {
  localStorage.setItem("tabskin-language", lang)
  document.documentElement.lang = lang
  updatePageContent(lang)
  updateLanguageButtons(lang)
}

function updatePageContent(lang) {
  const elements = document.querySelectorAll("[data-translate]")
  elements.forEach((element) => {
    const key = element.getAttribute("data-translate")
    if (translations[lang] && Object.prototype.hasOwnProperty.call(translations[lang], key)) {
      if (element.tagName === "TITLE" || element.tagName === "META") return
      element.innerHTML = translations[lang][key]
    }
  })

  updateTranslatedAttribute(lang, "data-translate-alt", "alt")
  updateTranslatedAttribute(lang, "data-translate-aria-label", "aria-label")
}

function updateTranslatedAttribute(lang, dataAttribute, targetAttribute) {
  document.querySelectorAll(`[${dataAttribute}]`).forEach((element) => {
    const key = element.getAttribute(dataAttribute)
    if (translations[lang] && Object.prototype.hasOwnProperty.call(translations[lang], key)) {
      element.setAttribute(targetAttribute, translations[lang][key])
    }
  })
}

function updateLanguageButtons(lang) {
  const buttons = document.querySelectorAll(".lang-btn")
  buttons.forEach((btn) => {
    const isActive = btn.getAttribute("data-lang") === lang
    btn.classList.toggle("active", isActive)
    btn.setAttribute("aria-pressed", String(isActive))
  })
}

